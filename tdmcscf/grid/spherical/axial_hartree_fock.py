def _occupation(value):
    if isinstance(value, AxialClosedShellOccupation):
        return value
    return AxialClosedShellOccupation(value)


def _validate_damping(value):
    if isinstance(value, (bool, np.bool_)) or not isinstance(
        value, (int, float, np.integer, np.floating)
    ):
        raise TypeError("damping must be a finite real scalar in [0, 1).")
    if not np.isfinite(value) or value < 0.0 or value >= 1.0:
        raise ValueError("damping must be a finite real scalar in [0, 1).")
    return float(value)


def _orthonormalize_rows(values):
    values = np.asarray(values)
    shape = values.shape
    flattened = values.reshape(len(values), -1)
    orthonormal, _ = np.linalg.qr(flattened.T)
    return orthonormal.T.reshape(shape)


def _align_rows(values, reference):
    values = np.asarray(values)
    shape = values.shape
    flattened = values.reshape(len(values), -1)
    reference = np.asarray(reference).reshape(len(reference), -1)
    overlap = flattened @ reference.conj().T
    left, _, right_h = np.linalg.svd(overlap)
    rotation = right_h.conj().T @ left.conj().T
    return (rotation @ flattened).reshape(shape)


class FixedDensityAxialFock:
    r"""Matrix-free restricted Fock operator generated by fixed orbitals."""

    def __init__(self, core, mean_fields, orbitals, orbital_m):
        self.core = core
        self.mean_fields = mean_fields
        self.orbitals = np.asarray(orbitals, dtype=np.complex128).copy()
        self.orbital_m = tuple(int(m) for m in orbital_m)
        if (
            self.orbitals.ndim != 3
            or self.orbitals.shape[1:] != core.orbital_shape
        ):
            raise ValueError(
                "orbitals must have shape (n_orbitals, *core.orbital_shape)."
            )
        if len(self.orbitals) != len(self.orbital_m):
            raise ValueError("orbital_m must contain one value per orbital.")
        self._indices = {
            m: np.asarray(
                [
                    i
                    for i, (_, channel_m) in enumerate(core.orbital_lm)
                    if channel_m == m
                ]
            )
            for m in range(-core.m_max, core.m_max + 1)
        }
        direct_pairs = tuple((j, j) for j in range(len(self.orbitals)))
        self.direct_fields = mean_fields.build(
            self.orbitals,
            pairs=direct_pairs,
            orbital_m=self.orbital_m,
        )

    def apply(self, orbitals, orbital_m):
        values = np.asarray(orbitals, dtype=np.complex128)
        single = values.ndim == 2
        if single:
            values = values[None, ...]
        if values.ndim != 3 or values.shape[1:] != self.core.orbital_shape:
            raise ValueError("orbitals have an incompatible orbital shape.")
        magnetic = np.asarray(orbital_m)
        if magnetic.ndim == 0:
            magnetic = np.repeat(magnetic, len(values))
        if magnetic.shape != (len(values),) or magnetic.dtype.kind not in "iu":
            raise ValueError("orbital_m must contain one integer per orbital.")
        magnetic = tuple(int(m) for m in magnetic)

        action = self.core.apply(values)
        for j in range(len(self.orbitals)):
            action += 2.0 * self.direct_fields.apply(
                values,
                (j, j),
                orbital_m=magnetic,
            )

        occupied_count = len(self.orbitals)
        combined = np.concatenate((self.orbitals, values), axis=0)
        combined_m = self.orbital_m + magnetic
        pairs = tuple(
            (j, occupied_count + p)
            for j in range(occupied_count)
            for p in range(len(values))
        )
        exchange_fields = self.mean_fields.build(
            combined,
            pairs=pairs,
            orbital_m=combined_m,
        )
        for p, _ in enumerate(magnetic):
            for j in range(occupied_count):
                action[p] -= exchange_fields.apply(
                    self.orbitals[j],
                    (j, occupied_count + p),
                    orbital_m=self.orbital_m[j],
                )
        return action[0] if single else action

    def apply_fixed_m(self, orbitals, m):
        shape = self.core.fixed_m_shape(m)
        values = np.asarray(orbitals, dtype=np.complex128)
        single = values.ndim == 2
        if single:
            values = values[None, ...]
        if values.ndim != 3 or values.shape[1:] != shape:
            raise ValueError(f"orbitals must have trailing shape {shape}.")
        full = np.zeros(
            (len(values), *self.core.orbital_shape), dtype=np.complex128
        )
        full[:, :, self._indices[int(m)]] = values
        action = self.apply(full, np.full(len(values), int(m)))
        result = action[:, :, self._indices[int(m)]]
        return result[0] if single else result

    def symmetric_linear_operator(self, m):
        shape = self.core.fixed_m_shape(m)
        size = int(np.prod(shape))

        def matvec(vector):
            symmetric = np.asarray(vector).reshape(shape)
            nodal = self.core.from_symmetric_fixed_m(symmetric, m)
            action = self.apply_fixed_m(nodal, m)
            return self.core.to_symmetric_fixed_m(action, m).ravel()

        return LinearOperator(
            (size, size),
            matvec=matvec,
            rmatvec=matvec,
            dtype=np.complex128,
        )


class _CombinedFock:
    def __init__(self, operators, coefficients):
        self.operators = tuple(operators)
        self.coefficients = np.asarray(coefficients)

    def apply(self, orbitals, orbital_m):
        return sum(
            coefficient * operator.apply(orbitals, orbital_m)
            for coefficient, operator in zip(
                self.coefficients, self.operators
            )
        )

    def apply_fixed_m(self, orbitals, m):
        return sum(
            coefficient * operator.apply_fixed_m(orbitals, m)
            for coefficient, operator in zip(
                self.coefficients, self.operators
            )
        )

    def symmetric_linear_operator(self, m):
        shape = self.operators[0].core.fixed_m_shape(m)
        size = int(np.prod(shape))
        core = self.operators[0].core

        def matvec(vector):
            symmetric = np.asarray(vector).reshape(shape)
            nodal = core.from_symmetric_fixed_m(symmetric, m)
            action = self.apply_fixed_m(nodal, m)
            return core.to_symmetric_fixed_m(action, m).ravel()

        return LinearOperator(
            (size, size),
            matvec=matvec,
            rmatvec=matvec,
            dtype=np.complex128,
        )


class _OperatorDIIS:
    def __init__(self, maximum_size):
        self.maximum_size = maximum_size
        self.operators = []
        self.errors = []

    def append(self, operator, error):
        self.operators.append(operator)
        self.errors.append(np.asarray(error).copy())
        if len(self.operators) > self.maximum_size:
            self.operators.pop(0)
            self.errors.pop(0)

    def coefficients(self):
        size = len(self.errors)
        system = np.empty((size + 1, size + 1))
        system[-1, :-1] = -1.0
        system[:-1, -1] = -1.0
        system[-1, -1] = 0.0
        for i, left in enumerate(self.errors):
            for j, right in enumerate(self.errors):
                system[i, j] = np.vdot(left, right).real
        rhs = np.zeros(size + 1)
        rhs[-1] = -1.0
        return np.linalg.solve(system, rhs)[:-1]

    def extrapolate(self):
        return _CombinedFock(self.operators, self.coefficients())


@dataclass
class AxialHartreeFockResult:
    """Result of a closed-shell axial molecular RHF calculation."""

    system: AxialDiatomic
    occupation: AxialClosedShellOccupation
    grid: object
    energy: float
    electronic_energy: float
    nuclear_repulsion_energy: float
    orbital_energies: np.ndarray
    orbitals: np.ndarray
    orbital_m: tuple[int, ...]
    orbital_labels: tuple[tuple[int, int], ...]
    l_populations: np.ndarray
    converged: bool
    iterations: int
    history: tuple[SCFIteration, ...]
    l_max: int
    m_max: int
    nuclear_L_max: int
    coulomb_L_max: int
    coulomb_M_max: int
    nuclear_method: str
    poisson_method: str
    diagonalization: str


class AxialHartreeFock:
    r"""Matrix-free RHF solver for a closed-shell axial diatomic system."""

    def __init__(
        self,
        system,
        occupation,
        *,
        radial_grid,
        l_max,
        m_max=None,
        nuclear_L_max=None,
        coulomb_L_max=None,
        coulomb_M_max=None,
        nuclear_method="analytic",
        poisson_method="inverse",
        max_iterations=100,
        conv_tol_e=1e-10,
        conv_tol_grad=1e-8,
        damping=0.2,
        diis=True,
        diis_start=3,
        diis_size=8,
        eigensolver_tolerance=1e-10,
        eigensolver_max_iterations=None,
    ):
        if not isinstance(system, AxialDiatomic):
            raise TypeError("system must be an AxialDiatomic.")
        self.system = system
        self.occupation = _occupation(occupation)
        if self.occupation.electron_count != system.electron_count:
            raise ValueError(
                "occupation electron count must equal the system electron count."
            )
        self.l_max = _integer(l_max, "l_max")
        self.m_max = (
            self.l_max if m_max is None else _integer(m_max, "m_max")
        )
        if self.m_max > self.l_max:
            raise ValueError("m_max cannot exceed l_max.")
        if self.m_max < self.occupation.occupied_m_max:
            raise ValueError("m_max must include every occupied magnetic sector.")
        self.nuclear_L_max = (
            2 * self.l_max
            if nuclear_L_max is None
            else _integer(nuclear_L_max, "nuclear_L_max")
        )
        self.coulomb_L_max = (
            2 * self.l_max
            if coulomb_L_max is None
            else _integer(coulomb_L_max, "coulomb_L_max")
        )
        default_M = min(
            self.coulomb_L_max,
            2 * self.occupation.occupied_m_max,
        )
        self.coulomb_M_max = (
            default_M
            if coulomb_M_max is None
            else _integer(coulomb_M_max, "coulomb_M_max")
        )
        if self.coulomb_L_max > 2 * self.l_max:
            raise ValueError("coulomb_L_max cannot exceed 2*l_max.")
        if self.coulomb_M_max > self.coulomb_L_max:
            raise ValueError("coulomb_M_max cannot exceed coulomb_L_max.")
        if self.coulomb_M_max < 2 * self.occupation.occupied_m_max:
            raise ValueError(
                "coulomb_M_max must include differences between occupied m sectors."
            )
        self.max_iterations = _integer(
            max_iterations, "max_iterations", minimum=1
        )
        self.conv_tol_e = _positive_real(conv_tol_e, "conv_tol_e")
        self.conv_tol_grad = (
            None
            if conv_tol_grad is None
            else _positive_real(conv_tol_grad, "conv_tol_grad")
        )
        self.damping = _validate_damping(damping)
        if not isinstance(diis, (bool, np.bool_)):
            raise TypeError("diis must be boolean.")
        self.diis = bool(diis)
        self.diis_start = _integer(diis_start, "diis_start", minimum=1)
        self.diis_size = _integer(diis_size, "diis_size", minimum=2)
        self.eigensolver_tolerance = _positive_real(
            eigensolver_tolerance, "eigensolver_tolerance"
        )
        self.eigensolver_max_iterations = (
            None
            if eigensolver_max_iterations is None
            else _integer(
                eigensolver_max_iterations,
                "eigensolver_max_iterations",
                minimum=1,
            )
        )
        self.diagonalization = "matrix-free"

        self.grid = radial_grid
        self.core = AxialCoreHamiltonian(
            radial_grid,
            self.l_max,
            self.m_max,
            system=system,
            nuclear_L_max=self.nuclear_L_max,
            nuclear_method=nuclear_method,
            poisson_method=poisson_method,
        )
        self.mean_fields = SphericalMeanFieldBuilder(
            radial_grid,
            self.l_max,
            self.m_max,
            L_max=self.coulomb_L_max,
            M_max=self.coulomb_M_max,
            poisson_method=poisson_method,
        )
        self.nuclear_method = nuclear_method
        self.poisson_method = poisson_method
        self.r = self.core.r
        self.radial_weights = self.core.radial_weights
        self.orbital_lm = self.core.orbital_lm
        self.orbital_shape = self.core.orbital_shape
        self._counts_by_m = dict(self.occupation.orbitals_per_m)
        self._occupied_m = tuple(self._counts_by_m)
        self._indices = {
            m: np.asarray(
                [
                    i
                    for i, (_, channel_m) in enumerate(self.orbital_lm)
                    if channel_m == m
                ]
            )
            for m in self._occupied_m
        }

    def _initial_orbitals(self):
        orbitals = {}
        for m, count in self._counts_by_m.items():
            shape = self.core.fixed_m_shape(m)
            size = int(np.prod(shape))
            if count >= size:
                raise ValueError("occupation exceeds the size of a magnetic block.")

            def matvec(vector):
                symmetric = np.asarray(vector).reshape(shape)
                nodal = self.core.from_symmetric_fixed_m(symmetric, m)
                action = self.core.apply_fixed_m(nodal, m)
                return self.core.to_symmetric_fixed_m(action, m).ravel()

            operator = LinearOperator(
                (size, size),
                matvec=matvec,
                rmatvec=matvec,
                dtype=np.complex128,
            )
            values, vectors = eigsh(
                operator,
                k=count,
                which="SA",
                v0=np.ones(size),
                tol=self.eigensolver_tolerance,
                maxiter=self.eigensolver_max_iterations,
            )
            order = np.argsort(values)
            orbitals[m] = vectors[:, order].T.reshape(
                count, *shape
            )
        return orbitals

    def _full_nodal(self, symmetric_orbitals):
        count = self.occupation.n_doubly_occupied
        full = np.zeros((count, *self.orbital_shape), dtype=np.complex128)
        orbital_m = []
        row = 0
        for m in self._occupied_m:
            nodal = self.core.from_symmetric_fixed_m(
                symmetric_orbitals[m], m
            )
            sector_count = len(nodal)
            full[row : row + sector_count, :, self._indices[m]] = nodal
            orbital_m.extend([m] * sector_count)
            row += sector_count
        return full, tuple(orbital_m)

    def _sector_symmetric(self, full_orbitals, orbital_m):
        sectors = {}
        magnetic = np.asarray(orbital_m)
        for m in self._occupied_m:
            selected = full_orbitals[magnetic == m][:, :, self._indices[m]]
            sectors[m] = self.core.to_symmetric_fixed_m(selected, m)
        return sectors

    def _evaluate(self, symmetric_orbitals):
        occupied, orbital_m = self._full_nodal(symmetric_orbitals)
        fock = FixedDensityAxialFock(
            self.core,
            self.mean_fields,
            occupied,
            orbital_m,
        )
        core_action = self.core.apply(occupied)
        fock_action = fock.apply(occupied, orbital_m)
        electronic = np.einsum(
            "pai,a,pai->",
            occupied.conj(),
            self.radial_weights,
            core_action + fock_action,
            optimize=True,
        )
        if abs(electronic.imag) > 1e-8:
            raise RuntimeError(
                "The RHF energy acquired a non-negligible imaginary part."
            )

        fock_symmetric = self._sector_symmetric(fock_action, orbital_m)
        residuals = []
        for m in self._occupied_m:
            orbitals = symmetric_orbitals[m]
            action = fock_symmetric[m]
            flat_orbitals = orbitals.reshape(len(orbitals), -1)
            flat_action = action.reshape(len(action), -1)
            occupied_fock = flat_orbitals.conj() @ flat_action.T
            residual = flat_action - occupied_fock.T @ flat_orbitals
            residuals.append(np.sqrt(2.0) * residual.ravel())
        error = np.concatenate(residuals)
        electronic = float(electronic.real)
        total = electronic + self.system.nuclear_repulsion_energy
        return total, electronic, float(np.linalg.norm(error)), fock, error

    def _diagonalize(self, fock, previous):
        updated = {}
        energies = {}
        for m, count in self._counts_by_m.items():
            operator = fock.symmetric_linear_operator(m)
            values, vectors = eigsh(
                operator,
                k=count,
                which="SA",
                v0=previous[m][0].ravel(),
                tol=self.eigensolver_tolerance,
                maxiter=self.eigensolver_max_iterations,
            )
            order = np.argsort(values)
            selected = vectors[:, order].T.reshape(
                count, *self.core.fixed_m_shape(m)
            )
            selected = _align_rows(selected, previous[m])
            updated[m] = selected
            energies[m] = values[order]
        return updated, energies

    def _canonicalize(self, orbitals, fock):
        occupied, orbital_m = self._full_nodal(orbitals)
        action = fock.apply(occupied, orbital_m)
        action_by_m = self._sector_symmetric(action, orbital_m)
        canonical = {}
        energies = {}
        for m in self._occupied_m:
            flat_orbitals = orbitals[m].reshape(len(orbitals[m]), -1)
            flat_action = action_by_m[m].reshape(len(action_by_m[m]), -1)
            matrix = flat_orbitals.conj() @ flat_action.T
            values, vectors = np.linalg.eigh(matrix)
            canonical[m] = (vectors.T @ flat_orbitals).reshape(
                orbitals[m].shape
            )
            energies[m] = values
        return canonical, energies

    def _mix_orbitals(self, updated, previous):
        if self.damping == 0.0:
            return updated
        mixed = {}
        for m in self._occupied_m:
            values = (1.0 - self.damping) * updated[m]
            values += self.damping * previous[m]
            mixed[m] = _orthonormalize_rows(values)
        return mixed

    def _result_arrays(self, orbitals, energies):
        full, orbital_m = self._full_nodal(orbitals)
        labels = []
        values = []
        for m in self._occupied_m:
            labels.extend(
                (index, m) for index in range(self._counts_by_m[m])
            )
            values.extend(energies[m])
        populations = np.zeros((len(full), self.l_max + 1))
        for channel, (l, _) in enumerate(self.orbital_lm):
            populations[:, l] += np.einsum(
                "pa,a,pa->p",
                full[:, :, channel].conj(),
                self.radial_weights,
                full[:, :, channel],
                optimize=True,
            ).real
        return full, orbital_m, tuple(labels), np.asarray(values), populations

    def solve(self):
        """Run matrix-free damped Roothaan/DIIS iterations."""

        orbitals = self._initial_orbitals()
        diis = _OperatorDIIS(self.diis_size)
        previous_fock = None
        previous_energy = None
        history = []
        converged = False
        raw_fock = None

        for iteration in range(1, self.max_iterations + 1):
            energy, _, gradient_norm, raw_fock, error = self._evaluate(
                orbitals
            )
            energy_change = (
                np.inf
                if previous_energy is None
                else abs(energy - previous_energy)
            )
            history.append(
                SCFIteration(iteration, energy, energy_change, gradient_norm)
            )
            if self.conv_tol_grad is not None:
                has_converged = gradient_norm < self.conv_tol_grad
            else:
                has_converged = (
                    previous_energy is not None
                    and energy_change < self.conv_tol_e
                )
            if has_converged:
                converged = True
                break
            if iteration == self.max_iterations:
                break

            diis.append(raw_fock, error)
            effective_fock = raw_fock
            used_diis = False
            if (
                self.diis
                and iteration >= self.diis_start
                and len(diis.operators) >= 2
            ):
                try:
                    effective_fock = diis.extrapolate()
                    used_diis = True
                except np.linalg.LinAlgError:
                    effective_fock = raw_fock
            if not used_diis and previous_fock is not None and self.damping:
                effective_fock = _CombinedFock(
                    (raw_fock, previous_fock),
                    (1.0 - self.damping, self.damping),
                )
            updated, _ = self._diagonalize(effective_fock, orbitals)
            orbitals = (
                updated
                if used_diis
                else self._mix_orbitals(updated, orbitals)
            )
            previous_fock = raw_fock
            previous_energy = energy

        orbitals, orbital_energies = self._canonicalize(orbitals, raw_fock)
        full, orbital_m, labels, energies, populations = self._result_arrays(
            orbitals,
            orbital_energies,
        )
        final_energy, electronic, final_gradient, _, _ = self._evaluate(
            orbitals
        )
        if not np.isclose(
            final_energy, history[-1].energy, rtol=0.0, atol=1e-12
        ):
            history.append(
                SCFIteration(
                    len(history) + 1,
                    final_energy,
                    abs(final_energy - history[-1].energy),
                    final_gradient,
                )
            )
        return AxialHartreeFockResult(
            system=self.system,
            occupation=self.occupation,
            grid=self.grid,
            energy=final_energy,
            electronic_energy=electronic,
            nuclear_repulsion_energy=self.system.nuclear_repulsion_energy,
            orbital_energies=energies,
            orbitals=full,
            orbital_m=orbital_m,
            orbital_labels=labels,
            l_populations=populations,
            converged=converged,
            iterations=len(history),
            history=tuple(history),
            l_max=self.l_max,
            m_max=self.m_max,
            nuclear_L_max=self.nuclear_L_max,
            coulomb_L_max=self.coulomb_L_max,
            coulomb_M_max=self.coulomb_M_max,
            nuclear_method=self.nuclear_method,
            poisson_method=self.poisson_method,
            diagonalization=self.diagonalization,
        )


class SphericalDiatomicHartreeFock(AxialHartreeFock):
    """High-level axial molecular RHF solver with FEM-DVR construction."""

    def __init__(
        self,
        system,
        occupation,
        *,
        nodes,
        n_points=15,
        l_max,
        m_max=None,
        **options,
    ):
        grid = make_spherical_femdvr_grid(nodes=nodes, n_points=n_points)
        super().__init__(
            system,
            occupation,
            radial_grid=grid,
            l_max=l_max,
            m_max=m_max,
            **options,
        )
